// Past the chipset <= 3 test bluetoothd clears the flag that makes it send LE Set Advertising
// Set Random Address (0x2035), so enabling a set that still uses a random own address answered
// 0x12. Only the "xor edi, edi; call" pair goes away; the chipset-0 test after it stays.
static const uint8_t addrClear[] = {
    0x83,0xb8,0x34,0x03,0x00,0x00,0x03,      // cmp dword [rax+0x334], 3
    0x77,0x2a,                               // ja  skip
    0x31,0xff,                               // xor edi,edi
    0xe8,0x3e,0x6b,0xce,0xff,                // call clear-flag
};
static const uint8_t addrClearPass[] = {
    0x83,0xb8,0x34,0x03,0x00,0x00,0x03,      // cmp dword [rax+0x334], 3
    0x77,0x2a,                               // ja  skip
    0x90,0x90,                               // xor edi,edi removed
    0x90,0x90,0x90,0x90,0x90,                // call removed
};
static_assert(sizeof(addrClear) == sizeof(addrClearPass), "rewrite size");
// Once extended advertising is in use a controller may refuse the legacy LE Create Connection
// (0x200d), and bluetoothd restarts its stack after enough refusals. This turns on
// gEnableExtendedCreateConnectionCommand (0x2043) by replacing the "movzbl slot, %edi" before
// its setter with "movl $1, %edi". The V2 command stays off.
static const uint8_t extConnProbe[] = {
    0x0f,0xb6,0xbd,0x5e,0xff,0xff,0xff,      // movzbl -0xa2(%rbp), %edi
    0xe8,0xcb,0x9d,0xcf,0xff,                // call setter
};
static const uint8_t extConnProbePass[] = {
    0xbf,0x01,0x00,0x00,0x00,0x90,0x90,      // movl $1, %edi; nop; nop
    0xe8,0xcb,0x9d,0xcf,0xff,                // call setter
};
static_assert(sizeof(extConnProbe) == sizeof(extConnProbePass), "rewrite size");
static_assert(sizeof(advProbe) == sizeof(advProbePass), "rewrite size");
static_assert(sizeof(scanProbe) == sizeof(scanProbePass), "rewrite size");
static const Rewrite kTahoe2671[] = {
    IBTP_SITE(advProbe, advProbePass, false),
    IBTP_SITE(addrClear, addrClearPass, false),
    IBTP_SITE(extConnProbe, extConnProbePass, false),
    IBTP_SITE(scanProbe, scanProbePass, true),
};

